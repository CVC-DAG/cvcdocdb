  /** *code* if it is a language of the table, otherwise "en". */
  function language(code) {
    return Object.prototype.hasOwnProperty.call(STRINGS, code) ? code : "en";
  }

  /** The text for *key* in *lang* (English if missing), with {name} filled from *params*. */
  function translate(lang, key, params) {
    var table = STRINGS[language(lang)];
    var text = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : STRINGS.en[key];
    if (text === undefined) return key;
    return text.replace(/\{(\w+)\}/g, function (match, name) {
      return params && Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match;
    });
  }

  var CvcdocdbI18n = { STRINGS: STRINGS, language: language, translate: translate };
  if (typeof module !== "undefined" && module.exports) module.exports = CvcdocdbI18n;
